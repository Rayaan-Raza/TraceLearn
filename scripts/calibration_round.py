"""Calibration round (H1 / G6): agreement on the 15 shared items and what to discuss.

    python scripts/calibration_round.py [--with-key]

Each rater labels the 15 calibration items **alone** in
``annotations/forms/calibration/answers_<rater>.csv`` (built by
``scripts/build_annotation_forms.py --forms calibration``). This script then
writes

* ``reports/calibration_round_report.md``: who answered, Fleiss κ over all raters,
  pairwise Cohen κ, every item with each rater's label, the class pairs people
  confused (what the decision tree must settle), and how often each label and
  UNCERTAIN were used;
* ``review/calibration/discussion.csv``: one row per item for the meeting, with
  every rater's label and blank ``agreed_label`` / ``decision_rule`` columns.
  The group fills those columns, then copies the rules into the decision tree in
  ``ANNOTATION_GUIDELINE.md``. Existing ``agreed_label`` / ``decision_rule`` /
  ``notes`` entries are kept when the script is re-run.

``--with-key`` adds what the weak-label rules said (from the hidden key). Use it
only **after** the discussion, so it cannot anchor anyone. The report holds no
student code, only item ids and labels, so it can be committed.

Readiness: κ ≥ 0.6 over all raters means the guideline is ready for the gold
round. Below that, the group revises the guideline from the discussion and
does a second round of 10 new items before gold annotation starts.
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from adjudicate_gold import UNCERTAIN, cohen_kappa, fleiss_kappa, majority  # noqa: E402
from codestream_common import DATASET_DIR  # noqa: E402

CAL_DIR = DATASET_DIR / "annotations" / "forms" / "calibration"
KEY = DATASET_DIR / "annotations" / "forms_key" / "gold_key.csv"
REPORT = DATASET_DIR / "reports" / "calibration_round_report.md"
DISCUSSION = DATASET_DIR / "review" / "calibration" / "discussion.csv"
READY_KAPPA = 0.6
KEEP_COLS = ("agreed_label", "decision_rule", "notes")


def read_rater_answers(cal_dir: Path) -> dict[str, dict[str, str]]:
    """{rater: {item_id: primary_label}} for every answers_<rater>.csv; blank answers skipped."""
    out: dict[str, dict[str, str]] = {}
    for p in sorted(cal_dir.glob("answers_*.csv")):
        rater = p.stem[len("answers_"):]
        with open(p, encoding="utf-8") as f:
            labels = {r["item_id"]: r["primary_label"].strip() for r in csv.DictReader(f)
                      if (r.get("primary_label") or "").strip()}
        out[rater] = labels
    return out


def analyse(answers: dict[str, dict[str, str]]) -> dict:
    raters = sorted(r for r, a in answers.items() if a)
    items = sorted({i for a in answers.values() for i in a})
    complete = [i for i in items if all(i in answers[r] for r in raters)]
    table = [[answers[r][i] for r in raters] for i in complete]
    per_item = []
    for i in items:
        labs = {r: answers[r].get(i, "") for r in raters}
        given = [v for v in labs.values() if v]
        top, k = (Counter(given).most_common(1)[0] if given else ("", 0))
        per_item.append({"item_id": i, "labels": labs, "agree": k, "answered": len(given),
                         "majority": majority(given) if given else UNCERTAIN,
                         "unanimous": bool(given) and k == len(given) == len(raters)})
    confusions: Counter = Counter()
    for it in per_item:
        distinct = sorted({v for v in it["labels"].values() if v})
        for a, b in combinations(distinct, 2):
            confusions[(a, b)] += 1
    pairs = {}
    for x, y in combinations(raters, 2):
        common = [i for i in items if i in answers[x] and i in answers[y]]
        pairs[(x, y)] = (len(common), cohen_kappa([answers[x][i] for i in common], [answers[y][i] for i in common]))
    usage = Counter(v for a in answers.values() for v in a.values())
    return {"raters": raters, "items": items, "complete": complete, "fleiss": fleiss_kappa(table),
            "per_item": per_item, "confusions": confusions, "pairs": pairs, "usage": usage}


def read_key(path: Path) -> dict[str, dict]:
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as f:
        return {r["item_id"]: r for r in csv.DictReader(f) if r["form"] == "calibration"}


def render_report(res: dict, key: dict[str, dict] | None = None) -> str:
    fk = res["fleiss"]
    raters = res["raters"]
    status = ("not measurable yet (needs ≥ 2 raters on the same items)" if fk is None else
              f"**{fk}**: {'ready for the gold round' if fk >= READY_KAPPA else 'revise the guideline, then a second round of 10 new items'}")
    L = ["# Calibration round report (H1 / G6)", "",
         "Generated by `scripts/calibration_round.py`. Do not edit by hand.", "",
         f"- Raters with answers: {len(raters)} ({', '.join(raters) or 'none'}); target 4 (3 team + external)",
         f"- Items: {len(res['items'])}, answered by every rater: {len(res['complete'])}",
         f"- Fleiss κ over all raters: {status} (readiness threshold {READY_KAPPA})",
         f"- Unanimous items: {sum(it['unanimous'] for it in res['per_item'])} · to discuss: "
         f"{sum(not it['unanimous'] for it in res['per_item'])}", "",
         "## Items", "",
         "| Item | " + " | ".join(raters) + " | Agree | Majority | Discuss |" + (" Rule said |" if key else ""),
         "|---|" + "---|" * len(raters) + "---:|---|---|" + ("---|" if key else "")]
    for it in res["per_item"]:
        cells = [it["labels"][r].replace("CPP_", "") or "—" for r in raters]
        row = f"| {it['item_id']} | " + " | ".join(cells) + f" | {it['agree']}/{len(raters)} | " \
              f"{it['majority'].replace('CPP_', '')} | {'' if it['unanimous'] else 'yes'} |"
        if key:
            k = key.get(it["item_id"], {})
            row += f" {(k.get('lf_label') or k.get('lf_decision') or '—').replace('CPP_', '')} |"
        L.append(row)
    L += ["", "## Class pairs people confused", "",
          "Each disagreement item counts once for every pair of different labels it got. These pairs are the "
          "branches the decision tree in `ANNOTATION_GUIDELINE.md` has to settle.", "",
          "| Labels | Items |", "|---|---:|"]
    L += [f"| {a.replace('CPP_', '')} vs {b.replace('CPP_', '')} | {n} |"
          for (a, b), n in res["confusions"].most_common()] or ["| none | 0 |"]
    L += ["", "## Pairwise agreement (descriptive)", "", "| Raters | Items | Cohen κ |", "|---|---:|---:|"]
    L += [f"| {x} – {y} | {n} | {k} |" for (x, y), (n, k) in res["pairs"].items()]
    L += ["", "## Label use", "", "| Label | Times chosen |", "|---|---:|"]
    L += [f"| {lab} | {n} |" for lab, n in sorted(res["usage"].items(), key=lambda t: (-t[1], t[0]))]
    if key:
        L += ["", "_The \"Rule said\" column comes from the hidden key; it was added after the discussion._"]
    return "\n".join(L) + "\n"


def write_discussion(res: dict, path: Path) -> None:
    kept = {}
    if path.exists():
        with open(path, encoding="utf-8") as f:
            kept = {r["item_id"]: r for r in csv.DictReader(f)}
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = ["item_id", *[f"label_{r}" for r in res["raters"]], "agree", "majority", *KEEP_COLS]
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols, lineterminator="\n")
        w.writeheader()
        for it in res["per_item"]:
            row = {"item_id": it["item_id"], "agree": f"{it['agree']}/{len(res['raters'])}",
                   "majority": it["majority"], **{f"label_{r}": it["labels"][r] for r in res["raters"]}}
            for c in KEEP_COLS:
                row[c] = kept.get(it["item_id"], {}).get(c, "")
            w.writerow(row)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cal-dir", type=Path, default=CAL_DIR)
    ap.add_argument("--with-key", action="store_true", help="add the weak-rule labels; only after discussion")
    a = ap.parse_args(argv)
    answers = read_rater_answers(a.cal_dir)
    if not any(answers.values()):
        print(f"no answers yet in {a.cal_dir}/answers_<rater>.csv")
        return 1
    res = analyse(answers)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(render_report(res, read_key(KEY) if a.with_key else None), encoding="utf-8")
    write_discussion(res, DISCUSSION)
    print(REPORT.read_text(encoding="utf-8"))
    print(f"discussion sheet: {DISCUSSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
