"""Which features tell synthetic training rows from real ones? (MODEL_IMPROVEMENT_PLAN P1, step 1)

    python scripts/eval_synthetic_shift.py [--variant execution]

Adversarial validation inside the training rows the served candidate trains on (train split, the
profile's row filter): a forest tries to tell synthetic rows from real rows with the served
variant's features, whole problems held out. It runs once over all rows and once inside each class
with at least 20 real and 20 synthetic rows. Within a class the label is fixed, so what still
separates the rows is how the code is written, not the bug. Features are ranked by how well each
alone separates the two groups (single-feature AUC, distance from 0.5).

The 6 Nov check (`eval_shift.py`) compared training rows with unseen real code on the retired
`best` and `common` columns. This one is on the served `execution` columns and inside the training
data, so it names the features that P1's style candidates drop. Writes
reports/shift_synthetic_real.json / .md. The held-out split is never read.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (ROOT, ROOT / "scripts"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import eval_candidate_oof as H  # noqa: E402
import train_xgb_misconception as T  # noqa: E402
from eval_shift import adversarial_auc, single_feature_separation, verdict  # noqa: E402

from backend.app.diagnosis.xgb_classifier import ModelClassifier  # noqa: E402

DS = ROOT / "data" / "misconception_dataset"
MIN_ROWS = 20


def split_matrix(rows, features: list[str]):
    X = np.array([[r["features"].get(f, np.nan) for f in features] for r in rows], dtype=float)
    real = np.array([r["real"] for r in rows])
    groups = np.array([r["cluster"] for r in rows])
    return X[real], X[~real], groups[real], groups[~real]


def run(variant: str = "execution", models_dir: Path = DS / "models") -> dict[str, Any]:
    model = ModelClassifier.load(variant, models_dir)
    metrics = json.loads((models_dir / "metrics_v1.json").read_text(encoding="utf-8"))
    cand = H.load_candidate({"name": "shift", "variant": variant})
    profile = H.configure_trainer(cand, (metrics.get("profile") or {}).get("name", "default"))
    try:
        rows = H.load_rows(cand, profile)
    finally:
        T.set_profile("default")
    features = model.features
    Xr, Xs, gr, gs = split_matrix(rows, features)
    overall = {**adversarial_auc(Xr, Xs, gr, gs), "top_features": single_feature_separation(Xr, Xs, features, top=25)}
    overall["verdict"] = verdict(overall["auc"])
    per_class = {}
    counts = Counter((r["label"], r["real"]) for r in rows)
    for cls in model.classes:
        if counts[(cls, True)] < MIN_ROWS or counts[(cls, False)] < MIN_ROWS:
            per_class[cls] = {"skipped": f"{counts[(cls, True)]} real / {counts[(cls, False)]} synthetic rows"}
            continue
        Xr, Xs, gr, gs = split_matrix([r for r in rows if r["label"] == cls], features)
        per_class[cls] = {**adversarial_auc(Xr, Xs, gr, gs), "top_features": single_feature_separation(Xr, Xs, features, top=10)}
    return {"variant": variant, "profile": profile, "n_features": len(features),
            "rows": {"real": int(sum(r["real"] for r in rows)), "synthetic": int(sum(not r["real"] for r in rows))},
            "overall": overall, "per_class": per_class}


def render(rep: dict[str, Any]) -> str:
    o = rep["overall"]
    lines = ["# Synthetic against real training rows (adversarial validation)", "",
             "Generated by `scripts/eval_synthetic_shift.py`. Do not edit by hand.", "",
             f"Variant `{rep['variant']}` ({rep['n_features']} features), profile `{rep['profile']}`, "
             f"{rep['rows']['real']} real and {rep['rows']['synthetic']} synthetic training rows. AUC 0.5 means the "
             "two look alike; the plan's gate for unseen code is under 0.75.", "",
             f"**All rows: AUC {o['auc']}** ({o['verdict']}).", "",
             "## Features that separate them most (all rows)", "",
             "Single-feature AUC; above 0.5 means larger on synthetic rows. Medians are real / synthetic.", "",
             "| Feature | AUC | Median real | Median synthetic |", "|---|---|---|---|"]
    for f in o["top_features"]:
        lines.append(f"| `{f['feature']}` | {f['auc']} | {f['median_train']} | {f['median_unseen']} |")
    lines += ["", "## Inside each class", "",
              "The label is the same on both sides, so what separates the rows is how the code is written.", "",
              "| Class | AUC | Real / synthetic | Strongest features |", "|---|---|---|---|"]
    for cls, e in rep["per_class"].items():
        if "skipped" in e:
            lines.append(f"| {cls.removeprefix('CPP_')} | not run | {e['skipped']} | - |")
        else:
            top = ", ".join(f"`{f['feature']}` {f['auc']}" for f in e["top_features"][:5])
            lines.append(f"| {cls.removeprefix('CPP_')} | {e['auc']} | {e['n_a']} / {e['n_b']} | {top} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--variant", default="execution")
    a = ap.parse_args(argv)
    rep = run(a.variant)
    out = DS / "reports"
    (out / "shift_synthetic_real.json").write_text(json.dumps(rep, indent=2) + "\n", encoding="utf-8", newline="\n")
    text = render(rep)
    (out / "shift_synthetic_real.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
